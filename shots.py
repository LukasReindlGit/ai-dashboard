"""Screenshots: images Claude sessions share with the user and images the user uploads for them.

They live on the host in SHOTS_DIR, mounted at the same path, so a path shown here is valid
for Claude on the host too:

    shared/<id>.<ext>   from a session, through the dashboard-screenshots skill (skill/share.sh)
    uploads/<id>.<ext>  from the user, attached in the terminal view or the Screenshots tab
    <id>.json           next to each image: session, session_created, cwd, caption, created

On start the skill (skill/ in this repo) is written into the host's ~/.claude/skills, with this
host's paths and URL filled in. Every Claude session on the host then knows how to share.
Images older than SHOTS_KEEP_DAYS are deleted, and the oldest go when the folder grows past SHOTS_MAX_MB.
"""

import hashlib
import json
import os
import re
import secrets
import threading
import time
from pathlib import Path

DIR = Path(os.environ.get("SHOTS_DIR", "/data/screenshots"))
KEEP_DAYS = float(os.environ.get("SHOTS_KEEP_DAYS") or 14)
MAX_MB = float(os.environ.get("SHOTS_MAX_MB") or 500)
SKILL_DIR = os.environ.get("SKILL_DIR", "")
SKILL_SRC = Path(__file__).parent / "skill"
MARKER = "Generated by ai-dashboard"
SOURCES = ("shared", "uploads")
ID = re.compile(r"^\d{8}-\d{6}-[0-9a-f]{1,16}$")
FILE = re.compile(r"^(\d{8}-\d{6}-[0-9a-f]{1,16})\.(png|jpg|webp|gif)$")
TYPES = {"png": "image/png", "jpg": "image/jpeg", "webp": "image/webp", "gif": "image/gif"}
MAX_UPLOAD = 20 * 1024 * 1024

LOCK = threading.Lock()
CACHE = {"key": None, "list": [], "pruned": 0}
STATUS = {"skill": None}


def sniff(head):
    """Image type from the first bytes. The extension alone doesn't decide what gets served."""
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    if head.startswith(b"\xff\xd8\xff"):
        return "jpg"
    if head[:6] in (b"GIF87a", b"GIF89a"):
        return "gif"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "webp"
    return None


def head_of(p):
    try:
        with open(p, "rb") as f:
            return f.read(12)
    except OSError:
        return b""


def read_meta(p):
    try:
        m = json.loads(p.read_text(errors="replace"))
        return m if isinstance(m, dict) else {}
    except (OSError, ValueError):
        return {}


def scan():
    out = []
    for src in SOURCES:
        try:
            names = os.listdir(DIR / src)
        except OSError:
            continue
        for n in names:
            m = FILE.match(n)
            if not m:
                continue
            img = DIR / src / n
            try:
                st = img.stat()
            except OSError:
                continue
            meta = read_meta(img.with_suffix(".json"))
            num = lambda k: meta.get(k) if isinstance(meta.get(k), (int, float)) else 0
            out.append({
                "id": m.group(1), "src": src, "ext": m.group(2), "file": str(img), "size": st.st_size,
                "from": "claude" if src == "shared" else "you",
                "session": str(meta.get("session") or "")[:60],
                "session_created": int(num("session_created")),
                "cwd": str(meta.get("cwd") or "")[:500],
                "caption": str(meta.get("caption") or "")[:500],
                "created": int(num("created") or st.st_mtime),
            })
    out.sort(key=lambda s: (s["created"], s["id"]), reverse=True)
    return out


def dir_key():
    key = []
    for src in SOURCES:
        try:
            key.append((DIR / src).stat().st_mtime_ns)
        except OSError:
            key.append(0)
    return tuple(key)


def remove(src, ident):
    for p in (DIR / src).glob(f"{ident}.*"):
        try:
            p.unlink()
        except OSError:
            pass


def prune(items):
    """Drop shots past KEEP_DAYS, then the oldest while the folder is over MAX_MB."""
    now, keep = time.time(), []
    for s in items:
        if KEEP_DAYS > 0 and now - s["created"] > KEEP_DAYS * 86400:
            remove(s["src"], s["id"])
        else:
            keep.append(s)
    total = sum(s["size"] for s in keep)
    while keep and MAX_MB > 0 and total > MAX_MB * 1024 * 1024:
        s = keep.pop()
        total -= s["size"]
        remove(s["src"], s["id"])
    for src in SOURCES:  # sidecars without an image, leftover .tmp files of an interrupted share
        for p in (DIR / src).glob("*"):
            try:
                orphan = p.suffix == ".json" and not any(p.with_suffix("." + e).exists() for e in TYPES)
                if (orphan or p.name.endswith(".tmp")) and now - p.stat().st_mtime > 3600:
                    p.unlink()
            except OSError:
                pass


def listing():
    """All shots, newest first. Cached until a file is added or removed in either folder."""
    with LOCK:
        if time.time() - CACHE["pruned"] > 600:
            CACHE["pruned"] = time.time()
            prune(scan())
        key = dir_key()
        if key != CACHE["key"]:
            CACHE["key"], CACHE["list"] = key, scan()
        return CACHE["list"]


def rev():
    """Changes whenever the list does, so the page only fetches the list when it changed."""
    listing()
    return hashlib.sha1(repr(CACHE["key"]).encode()).hexdigest()[:12]


def new_id():
    return time.strftime("%Y%m%d-%H%M%S") + "-" + secrets.token_hex(3)


def save_upload(data, session="", session_created=0, cwd="", caption=""):
    if len(data) > MAX_UPLOAD:
        raise ValueError(f"image too large (max {MAX_UPLOAD // 1024 // 1024} MB)")
    ext = sniff(data[:12])
    if not ext:
        raise ValueError("not a PNG, JPEG, WebP or GIF image")
    d = DIR / "uploads"
    d.mkdir(parents=True, exist_ok=True)
    ident = new_id()
    meta = {"id": ident, "session": session, "session_created": int(session_created or 0),
            "cwd": cwd, "caption": caption[:500], "created": int(time.time())}
    (d / f"{ident}.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n")
    tmp = d / f".{ident}.{ext}.tmp"
    tmp.write_bytes(data)
    tmp.replace(d / f"{ident}.{ext}")
    return str(d / f"{ident}.{ext}")


def delete(src, ident):
    if src not in SOURCES or not ID.match(ident or ""):
        raise ValueError("no such screenshot")
    remove(src, ident)


def file_for(src, name):
    """(path, content type) of a stored image, or None. Only images whose bytes match their name."""
    m = FILE.match(name or "")
    if src not in SOURCES or not m:
        return None
    p = DIR / src / name
    if not p.is_file() or sniff(head_of(p)) != m.group(2):
        return None
    return p, TYPES[m.group(2)]


def install_skill(url):
    """Write the dashboard-screenshots skill into SKILL_DIR (on the host: ~/.claude/skills/dashboard-screenshots).
    A SKILL.md there without our marker is someone's own and stays untouched."""
    for src in SOURCES:
        try:
            (DIR / src).mkdir(parents=True, exist_ok=True)
        except OSError as e:
            STATUS["skill"] = f"can't create {DIR / src}: {e.strerror}"
            return STATUS["skill"]
    if not SKILL_DIR:
        STATUS["skill"] = "SKILL_DIR is not set, so sessions don't get the skill"
        return STATUS["skill"]
    out = Path(SKILL_DIR)
    try:
        cur = (out / "SKILL.md").read_text()
        if MARKER not in cur:
            STATUS["skill"] = f"{out}/SKILL.md exists and isn't ours, left as it is"
            return STATUS["skill"]
    except OSError:
        pass
    subst = {"{{MARKER}}": MARKER, "{{SHOTS_DIR}}": str(DIR), "{{URL}}": url,
             "{{SCRIPT}}": str(out / "share.sh"), "{{KEEP_DAYS}}": f"{KEEP_DAYS:g}"}
    try:
        for name in ("SKILL.md", "share.sh"):
            text = (SKILL_SRC / name).read_text()
            for k, v in subst.items():
                text = text.replace(k, v)
            tmp = out / f".{name}.tmp"
            tmp.write_text(text)
            tmp.chmod(0o755 if name.endswith(".sh") else 0o644)
            tmp.replace(out / name)
    except OSError as e:
        STATUS["skill"] = f"can't write the skill to {out}: {e.strerror} (it must be writable by RUN_AS)"
        return STATUS["skill"]
    STATUS["skill"] = None
    return f"skill installed in {out}"


def info():
    return {"dir": str(DIR), "keep_days": KEEP_DAYS, "max_mb": MAX_MB,
            "skill": str(Path(SKILL_DIR) / "share.sh") if SKILL_DIR else None, "problem": STATUS["skill"]}
